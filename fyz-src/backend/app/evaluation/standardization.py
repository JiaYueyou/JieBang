def evaluate_standardization() -> dict[str, Any]:
    job_failures: list[dict[str, Any]] = []
    matched_fields = 0
    total_fields = 0
    exact_jobs = 0
    for index, case in enumerate(JOB_CASES, 1):
        actual = normalize_job_title(
            case["title"], city=case.get("city"), jd_text=case.get("jd_text")
        )
        expected = case["expected"]
        mismatches = {
            field: {"expected": value, "actual": getattr(actual, field)}
            for field, value in expected.items()
            if getattr(actual, field) != value
        }
        total_fields += len(expected)
        matched_fields += len(expected) - len(mismatches)
        exact_jobs += int(not mismatches)
        if mismatches:
            job_failures.append({"id": f"job-{index:03d}", "title": case["title"], "mismatches": mismatches})

    skill_failures: list[dict[str, Any]] = []
    skill_matches = 0
    unknown_matches = 0
    unknown_total = 0
    for index, (raw, expected) in enumerate(SKILL_CASES, 1):
        actual = normalize_skill(raw)
        matched = actual == expected
        skill_matches += int(matched)
        if expected is None:
            unknown_total += 1
            unknown_matches += int(matched)
        if not matched:
            skill_failures.append({"id": f"skill-{index:03d}", "input": raw, "expected": expected, "actual": actual})

    metrics = {
        "job_field_accuracy": round(matched_fields / total_fields, 6),
        "job_exact_accuracy": round(exact_jobs / len(JOB_CASES), 6),
        "skill_exact_accuracy": round(skill_matches / len(SKILL_CASES), 6),
        "skill_unknown_rejection_accuracy": round(unknown_matches / unknown_total, 6),
    }
    gates = {name: metrics[name] >= threshold for name, threshold in THRESHOLDS.items()}
    return {
        "dataset_version": DATASET_VERSION,
        "case_counts": {"jobs": len(JOB_CASES), "skills": len(SKILL_CASES)},
        "metrics": metrics,
        "thresholds": THRESHOLDS,
        "gates": gates,
        "passed": all(gates.values()),
        "failures": {"jobs": job_failures, "skills": skill_failures},
        "limitations": [
            "The versioned set is engineering-labelled and must not be presented as independent expert annotation.",
            "Job cases focus on supported technical-role and administrative-city boundaries.",
        ],
    }
